function t(key){
  const lang = getCurrentLang();
  return (TR[lang] && TR[lang][key]) || (TR.bn[key]) || key;
}

function getCurrentLang(){
  try{ return localStorage.getItem('giflab_lang') || 'bn'; } catch(e){ return window.__giflabLang || 'bn'; }
}

function setCurrentLang(lang){
  try{ localStorage.setItem('giflab_lang', lang); } catch(e){ window.__giflabLang = lang; }
}

function applyTranslations(){
  const lang = getCurrentLang();
  const meta = LANGS.find(l=>l.code===lang) || LANGS[0];
  document.documentElement.lang = lang;
  document.documentElement.dir = meta.dir;
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if(el.hasAttribute('data-i18n-placeholder')) el.setAttribute('placeholder', val);
    else if(el.tagName === 'INPUT' && el.getAttribute('type')==='text' && el.hasAttribute('data-i18n-value')) el.value = val;
    else el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
  const switcher = document.getElementById('langSwitch');
  if(switcher) switcher.value = lang;
}

function buildLangSwitcher(){
  const switcher = document.getElementById('langSwitch');
  if(!switcher) return;
  switcher.innerHTML = LANGS.map(l=>`<option value="${l.code}">${l.label}</option>`).join('');
  switcher.value = getCurrentLang();
  switcher.addEventListener('change', () => {
    setCurrentLang(switcher.value);
    applyTranslations();
  });
}

document.addEventListener('DOMContentLoaded', () => {
  buildLangSwitcher();
  applyTranslations();
});
